/**
 * Owners hold every staff permission in the catalogue (decision 0020) except named health data,
 * which is for the medical role (rule book §10.3); nobody edits this role.
 */
SCHOOL_ROLES.owner = {
  name: 'Owner',
  grants: Object.keys(CATALOGUE)
    .filter((p) => !NAMED_HEALTH.includes(p))
    .map((permission) => ({ permission })),
};

// Everyone may change their own photo, email and language; staff check themselves in and ask
// for their own leave.
// Relation 'self': their own record only.
for (const [key, role] of Object.entries(SCHOOL_ROLES)) {
  role.grants.push({ permission: 'people.profile.update_own', relation: 'self' });
  if (key !== 'parent')
    role.grants.push({ permission: 'staff.attendance.check_in', relation: 'self' });
  if (key !== 'parent') role.grants.push({ permission: 'staff.leave.apply', relation: 'self' });
  if (key !== 'parent') role.grants.push({ permission: 'helpdesk.ticket.raise', relation: 'self' });
  if (key !== 'parent') role.grants.push({ permission: 'people.appraisal.self', relation: 'self' });
  if (key !== 'parent') role.grants.push({ permission: 'payroll.slip.self', relation: 'self' });
  // Anyone answers the surveys meant for them (rule book §13.4).
  role.grants.push({ permission: 'survey.response.submit' });
  // Anyone may raise a grievance; parents only about their own children (rule book §13.11).
  role.grants.push(
    key === 'parent'
      ? { permission: 'grievance.case.raise', relation: 'guardian' }
      : { permission: 'grievance.case.raise' },
  );
  // Anyone on staff may raise an SOS at their school (rule book §16.5 step 3).
  if (key !== 'parent') role.grants.push({ permission: 'health.emergency.raise' });
}

/** Copies the templates into the current tenant. Returns role ids by key. Safe to repeat. */
export async function installRoles(tx: Tx): Promise<Record<string, string>> {
  const ids: Record<string, string> = {};
  for (const [key, role] of Object.entries(SCHOOL_ROLES)) {
    await tx.execute(sql`
      insert into role (org_id, key, name) values (app_current_org(), ${key}, ${role.name})
      on conflict (org_id, key) do nothing`);
    const [row] = await tx.execute<{ id: string }>(sql`
      select id::text from role where org_id = app_current_org() and key = ${key}`);
    if (!row) throw new Error(`installRoles: ${key} missing`);
    ids[key] = row.id;
    for (const g of role.grants) {
      await tx.execute(sql`
        insert into role_grant (org_id, role_id, permission, relation, guardian_flag)
        values (app_current_org(), ${row.id}, ${g.permission}, ${g.relation ?? null}, ${g.guardianFlag ?? null})
        on conflict do nothing`);
    }
  }
  return ids;
}
